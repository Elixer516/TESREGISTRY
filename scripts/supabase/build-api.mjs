/**
 * Bundles the `api` Edge Function — scripts/supabase/api-function.ts plus the
 * app's whole server — into supabase/functions/api/index.js.
 *
 *   npm run db:build-api
 *
 * Re-run after any change under src/server, then deploy the function.
 */

import { build } from 'esbuild';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

await build({
  entryPoints: [resolve(root, 'scripts/supabase/api-function.ts')],
  outfile: resolve(root, 'supabase/functions/api/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  alias: { '@': resolve(root, 'src') },
  external: ['npm:*'],
  // Image imports in shared modules are not used on the server.
  loader: { '.png': 'empty', '.svg': 'empty', '.jpg': 'empty' },
  banner: { js: '// Generated by scripts/supabase/build-api.mjs from src/server. Do not edit.' },
  logLevel: 'warning',
  plugins: [
    {
      // The demo dataset is never used on Supabase; see seed-stub.ts.
      name: 'seed-stub',
      setup(b) {
        b.onResolve({ filter: /\/data\/seed$/ }, () => ({ path: resolve(root, 'scripts/supabase/seed-stub.ts') }));
      },
    },
  ],
});
console.log('built supabase/functions/api/index.js');
